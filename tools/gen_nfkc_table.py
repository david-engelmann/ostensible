"""Generate src/nfkc_tables.txt, the normalization data of PORT20,
from the interpreter's own unicodedata module.

Usage: python3 tools/gen_nfkc_table.py > src/nfkc_tables.txt

The arbiter of this port is CPython 3.12.3, whose unicodedata
stands at Unicode 15.0.0, and this generator refuses to run
against any other version, so the table can only ever carry the
arbiter's own data. Three line forms stand in the file. A D line
carries a codepoint and its immediate decomposition, canonical
and compatibility alike, the Hangul syllables standing under
their algorithmic decomposition in the port and so carrying no
line. A C line carries a codepoint and its canonical combining
class where that class is not zero. A P line carries the two
codepoints of a composition pair and the codepoint they compose
to, the pairs standing drawn from the canonical decompositions
of length two with the composition exclusions removed and the
Hangul compositions standing algorithmic in the port.
"""
import sys
import unicodedata

if unicodedata.unidata_version != "15.0.0":
    raise SystemExit(
        "unicodedata stands at %s, the arbiter's 15.0.0 is required"
        % unicodedata.unidata_version
    )

HANGUL_FIRST = 0xAC00
HANGUL_LAST = 0xD7A3

decomp = {}
ccc = {}
for cp in range(0x110000):
    ch = chr(cp)
    d = unicodedata.decomposition(ch)
    if d and not (HANGUL_FIRST <= cp <= HANGUL_LAST):
        fields = [p for p in d.split() if not p.startswith("<")]
        decomp[cp] = tuple(int(p, 16) for p in fields)
    c = unicodedata.combining(ch)
    if c:
        ccc[cp] = c

exclusions = set()
for cp, parts in decomp.items():
    if len(parts) == 1:
        exclusions.add(cp)
# The full composition exclusion set also carries chars whose
# decomposition the standard marks excluded even at length two.
# unicodedata exposes it only through the NFC check, so rebuild
# it the way the standard states it. A char is excluded exactly
# where NFC of its decomposition differs from the char itself.
for cp, parts in decomp.items():
    if len(parts) == 2:
        if unicodedata.normalize("NFC", "".join(chr(p) for p in parts)) != chr(cp):
            exclusions.add(cp)

pairs = {}
for cp, parts in decomp.items():
    if len(parts) == 2 and cp not in exclusions:
        pairs[parts] = cp

out = []
out.append("# nfkc_tables.txt, generated by tools/gen_nfkc_table.py")
out.append("# from unicodedata 15.0.0, the arbiter's database. Do not edit.")
for cp in sorted(decomp):
    out.append("D %04X %s" % (cp, " ".join("%04X" % p for p in decomp[cp])))
for cp in sorted(ccc):
    out.append("C %04X %d" % (cp, ccc[cp]))
for parts in sorted(pairs):
    out.append("P %04X %04X %04X" % (parts[0], parts[1], pairs[parts]))
sys.stdout.write("\n".join(out) + "\n")
